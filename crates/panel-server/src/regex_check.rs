//! 正则照内核编译一遍 / Regexes compiled as the kernel compiles them
//!
//! 内核读配置时用 regex 库原样编译正则（不加大小写、不加锚点），编不出来整份配置不收：
//! - 域名的正则（规则和入口的 `domain_regex`、回答条件的 `request_domain_regex`，kixdns matcher/mod.rs `domain_regex`）：
//!   状态空间和 DFA 各 1 MB；
//! - TXT 内容的正则（`response_txt_content` 的 regex，matcher/mod.rs `ResponseTxtContent`）：先看长度，超过 1000 字节不收，
//!   再照域名正则的 1 MB 编译（kixdns #219 起；以前限在 1000 字节，`.`、`\d+` 都编译不过），编不出的原因前面加
//!   「invalid regex: 」；
//! - 拦截列表合并文件里的 `regexp:`（`GeoSite` JSON，matcher/geosite.rs `compile_geosite_regex`）：先把 `\w`、`\d`、`\s`、`\b`
//!   改成 Go 的 ASCII 写法（数据是写给 v2ray 的），再照 1 MB 编译；编不出的那条内核跳过，别的照用。
//!
//! 这里用同一个库、同样的上限编译，回答和内核一样。regex、regex-automata、regex-syntax 的版本和最新的内核（tuoro/kixdns 的
//! main）的 Cargo.lock 一样（CI 每次拿 main 此刻的那一版比一遍，见 scripts/check-kernel-regex-versions.py）；`testdata/kernel-regex.json` 是拿内核跑出来的用例
//! （scripts/kernel-regex-cases.py 重新生成），页面（web/src/config-model/regex-check.ts）也用它测。
//!
//! regex-syntax 先把整个正则展开成语法树，大小上限要到编译时才起作用：`\w`、`\pL` 每个都展开成几 KB 的 Unicode 字符类，
//! 几 MB 这样的写法能吃掉几 GB 内存。所以这里只编译 [`MAX_CHECKED_BYTES`] 以内的；更长的不下结论（域名的正则保存时内核自己再查，
//! 拦截列表里的不用）。
//!
//! When the kernel reads a config it compiles regexes as written with the regex library (no case folding or anchors added), and
//! one that does not compile makes the whole config refused; the limits differ by place:
//! - name regexes (`domain_regex` in rules and entries, `request_domain_regex` in answer conditions, kixdns matcher/mod.rs
//!   `domain_regex`): 1 MB each for the state space and the DFA;
//! - TXT content regexes (`response_txt_content` in regex mode, matcher/mod.rs `ResponseTxtContent`): over 1000 bytes long is
//!   refused before compiling, then it compiles within the 1 MB of name regexes (since kixdns #219; it used to be held to 1000
//!   bytes, which `.` or `\d+` already exceed), the cause of a refusal prefixed with 「invalid regex: 」;
//! - `regexp:` entries in the blocklists' merged file (`GeoSite` JSON, matcher/geosite.rs `compile_geosite_regex`): `\w`, `\d`,
//!   `\s` and `\b` first take their Go ASCII meaning (the data is written for v2ray), then it compiles within 1 MB; one that does
//!   not compile is skipped by the kernel and the rest stay in use.
//!
//! This compiles with the same library and limits and answers as the kernel does. The versions of regex, regex-automata and
//! regex-syntax are those of the latest kernel's Cargo.lock (tuoro/kixdns main; CI compares them with main as it stands on every
//! run, see scripts/check-kernel-regex-versions.py); `testdata/kernel-regex.json` holds cases run through the kernel (regenerated by
//! scripts/kernel-regex-cases.py), and the page (web/src/config-model/regex-check.ts) is tested on it too.
//!
//! regex-syntax spells the whole regex out as a syntax tree first, and the size limits only apply once it compiles: every `\w` or
//! `\pL` becomes a Unicode class of several KB, so a few MB of them can take gigabytes. Only regexes up to [`MAX_CHECKED_BYTES`]
//! are compiled here; a longer one gets no verdict (a name regex is checked by the kernel itself on save, a blocklist's goes
//! unused).

use std::borrow::Cow;

use serde::{Deserialize, Serialize};

/// 内核编译正则的上限（域名的、TXT 的、`GeoSite` 的都一样）：状态空间和 DFA 各 1 MB / The kernel's limits for compiling a regex
/// (the same for names, TXT and `GeoSite`): 1 MB each for the state space and the DFA
const SIZE_LIMIT: usize = 1_000_000;
/// 内核的 TXT 正则最长 1000 字节 / The kernel's TXT regexes are at most 1000 bytes long
const TXT_MAX_LEN: usize = 1000;

/// 这里最多编译这么长的正则（字节）。能编译出来的域名正则远比这短：`\w` 连写到 116 字节、`\pL` 连写不到 100 字节就超出 1 MB，
/// 一个域名最长 253 字节；只有几千个字母的纯文字才编得出来，那不是写正则的样子。和页面的 `REGEX_CHECK_MAX_BYTES` 一样
/// The longest regex compiled here, in bytes. Name regexes that compile are far shorter: `\w` written out passes 1 MB by 116 bytes
/// and `\pL` before 100, and a name is at most 253 bytes; only plain text of thousands of letters still compiles, which is no
/// regex anyone writes. The same as the page's `REGEX_CHECK_MAX_BYTES`
pub const MAX_CHECKED_BYTES: usize = 16 * 1024;

/// 正则用在哪儿：TXT 的先看长度，原因的说法也不一样 / Where a regex is used: a TXT one's length is looked at first, and a refusal is
/// worded its own way
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Kind {
    /// 域名的正则 / A name regex
    Domain,
    /// TXT 内容的正则 / A TXT content regex
    Txt,
}

/// 内核为什么不收 / Why the kernel refuses it
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum Cause {
    /// 写法不对 / Written wrong
    Syntax,
    /// 编译出来超过上限 / Over the limit once compiled
    TooBig,
    /// 比 TXT 正则的长度上限长 / Longer than a TXT regex may be
    TooLong,
}

/// 内核对一个正则的回答 / The kernel's answer for one regex
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(tag = "verdict", rename_all = "kebab-case")]
pub enum Answer {
    /// 编得出来 / It compiles
    Compiles,
    /// 编不出来：原因和内核报的原话（去掉前面的「compile configuration: 」） / It does not: why, and the kernel's words (without
    /// the leading 「compile configuration: 」)
    Refused { cause: Cause, error: String },
    /// 太长，这里不编译，不下结论 / Too long to compile here: no verdict
    Unchecked { reason: String },
}

/// 内核对这个正则的回答 / The kernel's answer for this regex
#[must_use]
pub fn answer(kind: Kind, pattern: &str) -> Answer {
    match kind {
        Kind::Domain if pattern.len() > MAX_CHECKED_BYTES => Answer::Unchecked {
            reason: format!(
                "正则超过 {}\u{a0}KiB，这里不查，保存时 KixDNS 自己查",
                MAX_CHECKED_BYTES / 1024
            ),
        },
        Kind::Domain => match compile(pattern, SIZE_LIMIT) {
            Ok(()) => Answer::Compiles,
            Err((cause, error)) => Answer::Refused { cause, error },
        },
        // 内核先看长度，不编译：再长也不花什么 / The kernel looks at the length first, without compiling: however long, it costs
        // nothing
        Kind::Txt if pattern.len() > TXT_MAX_LEN => Answer::Refused {
            cause: Cause::TooLong,
            error: format!(
                "regex pattern too long: {} bytes (max {TXT_MAX_LEN})",
                pattern.len()
            ),
        },
        Kind::Txt => match compile(pattern, SIZE_LIMIT) {
            Ok(()) => Answer::Compiles,
            Err((cause, error)) => Answer::Refused {
                cause,
                error: format!("invalid regex: {error}"),
            },
        },
    }
}

/// 拦截列表合并文件里的一条 `regexp:` 内核用不用得上：用得上为 None，不然是原因。比 [`MAX_CHECKED_BYTES`] 长的不编译，
/// 算 [`Cause::TooLong`]：面板不把它写进合并文件
/// Whether the kernel can use one `regexp:` entry of the blocklists' merged file: None when it can, otherwise why not. One longer
/// than [`MAX_CHECKED_BYTES`] is not compiled and counts as [`Cause::TooLong`]: the panel leaves it out of the merged file
#[must_use]
pub fn blocklist_problem(pattern: &str) -> Option<Cause> {
    if pattern.len() > MAX_CHECKED_BYTES {
        return Some(Cause::TooLong);
    }
    compile(&geosite_pattern(pattern), SIZE_LIMIT)
        .err()
        .map(|(cause, _)| cause)
}

/// 照内核的写法编译：状态空间和 DFA 用同一个上限 / Compiles as the kernel does: one limit for both the state space and the DFA
fn compile(pattern: &str, limit: usize) -> Result<(), (Cause, String)> {
    regex::RegexBuilder::new(pattern)
        .size_limit(limit)
        .dfa_size_limit(limit)
        .build()
        .map(drop)
        .map_err(|error| {
            let cause = match error {
                regex::Error::CompiledTooBig(_) => Cause::TooBig,
                _ => Cause::Syntax,
            };
            (cause, error.to_string())
        })
}

/// 内核实际编译的 `GeoSite` 正则（kixdns matcher/geosite.rs `compile_geosite_regex`）：改成 Go 写法以后语法对就用它，
/// 不然用原样
/// The `GeoSite` regex the kernel actually compiles (kixdns matcher/geosite.rs `compile_geosite_regex`): the Go rewrite when its
/// syntax holds, the pattern as written otherwise
fn geosite_pattern(pattern: &str) -> Cow<'_, str> {
    match go_classes(pattern) {
        Cow::Owned(rewritten) if regex_syntax::Parser::new().parse(&rewritten).is_ok() => {
            Cow::Owned(rewritten)
        }
        _ => Cow::Borrowed(pattern),
    }
}

/// `pattern` 里的 `\w`、`\d`、`\s`、`\b` 及其大写的取反形式改成 Go 正则的 ASCII 含义：字符类外写成一个字符类
/// （`\b` 写成 `(?-u:\b)`），字符类里展开成范围（取反的写成嵌套的字符类）。转义的反斜杠和别的转义原样保留。
/// 照抄 kixdns matcher/geosite.rs `go_classes`
/// `\w`, `\d`, `\s` and `\b` in `pattern`, and their negated capitals, rewritten to their ASCII meaning in Go regexes: outside a
/// class each becomes a class (`\b` becomes `(?-u:\b)`), inside a class it becomes ranges (a negated one a nested class).
/// Escaped backslashes and other escapes stay as they are. Copied from kixdns matcher/geosite.rs `go_classes`
fn go_classes(pattern: &str) -> Cow<'_, str> {
    const WORD: &str = "0-9A-Za-z_";
    const DIGIT: &str = "0-9";
    const SPACE: &str = r"\t\n\f\r ";
    if !pattern.contains('\\') {
        return Cow::Borrowed(pattern);
    }
    let mut out = String::with_capacity(pattern.len() + 16);
    let mut changed = false;
    // 字符类嵌套的层数，和刚开始一个字符类（这时的 `]` 是字面字符） / How deep in character classes, and whether one just began
    // (where `]` is a literal)
    let (mut depth, mut class_start) = (0usize, false);
    let mut chars = pattern.chars();
    while let Some(c) = chars.next() {
        let starting = std::mem::take(&mut class_start);
        match c {
            '\\' => {
                let Some(next) = chars.next() else {
                    out.push(c);
                    break;
                };
                let class = match next.to_ascii_lowercase() {
                    'w' => Some(WORD),
                    'd' => Some(DIGIT),
                    's' => Some(SPACE),
                    _ => None,
                };
                match (class, next.is_ascii_uppercase(), depth > 0) {
                    (Some(class), false, true) => out.push_str(class),
                    (Some(class), negated, _) => {
                        out.push_str(if negated { "[^" } else { "[" });
                        out.push_str(class);
                        out.push(']');
                    }
                    (None, _, false) if matches!(next, 'b' | 'B') => {
                        out.push_str("(?-u:\\");
                        out.push(next);
                        out.push(')');
                    }
                    _ => {
                        out.push(c);
                        out.push(next);
                        continue;
                    }
                }
                changed = true;
            }
            '[' => {
                depth += 1;
                class_start = true;
                out.push(c);
            }
            '^' if starting => {
                class_start = true;
                out.push(c);
            }
            ']' if depth > 0 && !starting => {
                depth -= 1;
                out.push(c);
            }
            _ => out.push(c),
        }
    }
    if changed {
        Cow::Owned(out)
    } else {
        Cow::Borrowed(pattern)
    }
}

#[cfg(test)]
mod tests {
    use super::{Answer, Cause, Kind, MAX_CHECKED_BYTES, answer, blocklist_problem, go_classes};

    #[derive(serde::Deserialize)]
    struct Case {
        kind: Kind,
        pattern: String,
        error: Option<String>,
    }

    #[derive(serde::Deserialize)]
    struct BlocklistCase {
        pattern: String,
        used: bool,
    }

    #[derive(serde::Deserialize)]
    struct Table {
        patterns: Vec<Case>,
        blocklist: Vec<BlocklistCase>,
    }

    fn table() -> Table {
        serde_json::from_str(include_str!("../../../testdata/kernel-regex.json")).unwrap()
    }

    /// 编不出的原因从内核的原话看得出来 / The cause of a refusal can be told from the kernel's words
    fn cause_of(error: &str) -> Cause {
        if error.starts_with("regex pattern too long") {
            Cause::TooLong
        } else if error.contains("exceeds size limit") {
            Cause::TooBig
        } else {
            Cause::Syntax
        }
    }

    /// 每一条都和内核的回答一样，原因一字不差 / Every answer is the kernel's, the cause word for word
    #[test]
    fn answers_as_the_kernel() {
        let table = table();
        let differ: Vec<(Kind, &str)> = table
            .patterns
            .iter()
            .filter(|case| {
                let expected =
                    case.error
                        .clone()
                        .map_or(Answer::Compiles, |error| Answer::Refused {
                            cause: cause_of(&error),
                            error,
                        });
                answer(case.kind, &case.pattern) != expected
            })
            .map(|case| (case.kind, case.pattern.as_str()))
            .collect();
        assert!(differ.is_empty(), "{differ:?}");
    }

    /// 拦截列表里的正则照内核读 `GeoSite` 的办法：哪条用得上和内核一样 / Blocklist regexes as the kernel reads `GeoSite`: the same
    /// ones are of use as in the kernel
    #[test]
    fn blocklist_regexes_are_used_as_the_kernel_uses_them() {
        let table = table();
        let differ: Vec<&str> = table
            .blocklist
            .iter()
            .filter(|case| blocklist_problem(&case.pattern).is_none() != case.used)
            .map(|case| case.pattern.as_str())
            .collect();
        assert!(differ.is_empty(), "{differ:?}");
        assert_eq!(
            blocklist_problem(r"^ad\pL{60}\.example\.com$"),
            Some(Cause::TooBig)
        );
        assert_eq!(blocklist_problem("(unclosed"), Some(Cause::Syntax));
    }

    /// 长度上限两边都算上：正好到上限的照编译，多一个字节不下结论；TXT 的长度先看，再长也给内核的回答
    /// The length cap counts both ways: one right at the cap is compiled, a byte more gets no verdict; a TXT regex's length is
    /// looked at first, so however long it gets the kernel's answer
    #[test]
    fn a_long_regex_is_not_compiled() {
        let at_cap = "a".repeat(MAX_CHECKED_BYTES);
        assert_eq!(answer(Kind::Domain, &at_cap), Answer::Compiles);
        let words = r"\w".repeat(MAX_CHECKED_BYTES / 2);
        assert!(matches!(
            answer(Kind::Domain, &words),
            Answer::Refused {
                cause: Cause::TooBig,
                ..
            }
        ));
        let over = format!("{at_cap}a");
        assert!(matches!(
            answer(Kind::Domain, &over),
            Answer::Unchecked { .. }
        ));
        assert_eq!(blocklist_problem(&over), Some(Cause::TooLong));
        let long_txt = r"\pL".repeat(1_000_000);
        assert_eq!(
            answer(Kind::Txt, &long_txt),
            Answer::Refused {
                cause: Cause::TooLong,
                error: "regex pattern too long: 3000000 bytes (max 1000)".to_owned()
            }
        );
    }

    /// 和内核的 `go_classes` 同一组用例 / The same cases as the kernel's `go_classes`
    #[test]
    fn geosite_classes_are_rewritten_the_go_way() {
        for (pattern, rewritten) in [
            (r"cdn\d-x", r"cdn[0-9]-x"),
            (r"^\w{5}\.com$", r"^[0-9A-Za-z_]{5}\.com$"),
            (r"a\Sb\Dc\Wd", r"a[^\t\n\f\r ]b[^0-9]c[^0-9A-Za-z_]d"),
            (r"[\w-]+", r"[0-9A-Za-z_-]+"),
            (r"[^\d.]", r"[^0-9.]"),
            (r"[a\W]", r"[a[^0-9A-Za-z_]]"),
            (r"[]\d]", r"[]0-9]"),
            (r"[[:alpha:]\d]x\d", r"[[:alpha:]0-9]x[0-9]"),
            (r"\bfoo\B", r"(?-u:\b)foo(?-u:\B)"),
            (r"\\d", r"\\d"),
            (r"\p{L}\.\[\d\]", r"\p{L}\.\[[0-9]\]"),
        ] {
            assert_eq!(go_classes(pattern), rewritten, "{pattern}");
        }
        assert!(matches!(
            go_classes(r"plain\.com$"),
            std::borrow::Cow::Borrowed(_)
        ));
    }
}
